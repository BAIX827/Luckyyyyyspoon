"""Rebuild the overview texture from the same inventory art used in the close-up."""
from pathlib import Path

from PIL import Image


ASSETS = Path(__file__).resolve().parents[1] / "Game" / "assets"
COLORS = ("pink", "blue", "purple", "yellow", "green", "orange")
CELL = 98
LIMIT = CELL - 2  # Transparent gutter between neighboring products.


def source(color, kind, variant):
    if kind in (0, 14):
        fixture = "band" if kind == 0 else "roll"
        return ASSETS / "counter" / f"{fixture}-{color}.webp"
    return ASSETS / "items" / f"{color}-{kind}-{variant}.png"


def build():
    styles = sorted(tuple(map(int, p.stem.split("-")[1:])) for p in (ASSETS / "items").glob("pink-*.png"))
    width, height = CELL * len(COLORS), CELL * len(styles)
    atlas = Image.new("RGBA", (width, height))
    rules = ["/* Generated by tools/build_shelf_preview.py. */"]
    for row, (kind, variant) in enumerate(styles):
        selector = f'.shelf-world [data-kind="{kind}"][data-variant="{variant}"]'
        first = None
        for col, color in enumerate(COLORS):
            with Image.open(source(color, kind, variant)) as src:
                sprite = src.convert("RGBA")
            ratio = sprite.width / sprite.height
            sprite.thumbnail((LIMIT, LIMIT), Image.Resampling.NEAREST)
            atlas.paste(sprite, (col * CELL, row * CELL))
            w, h = sprite.size
            if first == (ratio, w, h):
                continue
            target = selector if col == 0 else selector + f" .rack-slot:nth-child({col+1})"
            if col == 0:
                first = (ratio, w, h)
            rules.append(
                f'{target}{{--ratio:{ratio:.6f};--sheet-size:{100*width/w:.6f}% {100*height/h:.6f}%;'
                f'--step-x:{100*CELL/(width-w):.6f}%;--sheet-y:{100*row*CELL/(height-h):.6f}%}}'
            )
    output = ASSETS / "counter"
    atlas.save(output / "stock-preview.webp", lossless=True, method=6)
    (output / "stock-preview.css").write_text("\n".join(rules) + "\n", encoding="utf-8")


if __name__ == "__main__":
    build()
